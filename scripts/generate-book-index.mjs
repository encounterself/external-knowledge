import fs from 'node:fs';
import path from 'node:path';

const source = path.resolve('books/867-chushi-notes/.cangjie/source/structured.md');
const output = path.resolve('src/book-index.ts');
const text = fs.readFileSync(source, 'utf8').replace(/\r\n/g, '\n');
const chunks = text.split(/^===== PAGE (\d+) =====\s*$/m);
const pages = [];
for (let i = 1; i < chunks.length; i += 2) {
  const page = Number(chunks[i]);
  const raw = chunks[i + 1].trim();
  if (!raw) continue;
  const lines = raw.split('\n');
  const headings = lines.filter((line) => /^(#{1,6})\s+/.test(line) || /^(第[一二三四五六七八九十百]+章)\s*/.test(line));
  const title = headings.find((line) => /^#\s+/.test(line))?.replace(/^#\s*/, '').trim() || headings[0]?.replace(/^#+\s*/, '').trim() || `第 ${page} 页`;
  pages.push({ page, title, text: raw, headings });
}
const chapters = [];
for (const page of pages) {
  const matches = page.text.match(/^#\s+(.+)$/gm) ?? [];
  for (const match of matches) {
    const title = match.replace(/^#\s+/, '').trim();
    if (!chapters.some((item) => item.title === title)) chapters.push({ title, page: page.page });
  }
}
const normalizedPages = pages.map((page, index) => ({
  ...page,
  chapter: chapters.slice().reverse().find((chapter) => chapter.page <= page.page)?.title ?? null,
  sourceAnchor: `structured.md#page-${page.page}`,
  searchText: `${page.title}\n${page.text}`.replace(/\s+/g, ' ').trim(),
  wordCount: page.text.replace(/[`*_>#-]/g, ' ').split(/\s+/).filter(Boolean).length,
}));
const normalizedChapters = chapters.map((chapter, index) => ({
  ...chapter,
  endPage: chapters[index + 1]?.page ? chapters[index + 1].page - 1 : pages.at(-1)?.page ?? chapter.page,
  sourceAnchor: `structured.md#page-${chapter.page}`,
}));
const content = `// Generated by scripts/generate-book-index.mjs from structured.md.\nexport type BookPage = { page: number; title: string; text: string; headings: string[]; chapter: string | null; sourceAnchor: string; searchText: string; wordCount: number };\nexport type BookChapter = { title: string; page: number; endPage: number; sourceAnchor: string };\nexport const bookSource = 'books/867-chushi-notes/.cangjie/source/structured.md';\nexport const bookPages: BookPage[] = ${JSON.stringify(normalizedPages)};\nexport const bookChapters: BookChapter[] = ${JSON.stringify(normalizedChapters)};\n`;
fs.writeFileSync(output, content);
console.log(`Generated ${pages.length} pages and ${chapters.length} chapters → ${output}`);

function chapterParagraphs(pages) {
  const lines = pages.flatMap((page) => page.text.split('\n')).map((line) => line.trim()).filter(Boolean);
  const paragraphs = [];
  let current = '';
  const isHeading = (line) => /^#{1,6}\s+/.test(line) || /^\d+(\.\d+)*\s*[^：:]+$/.test(line) || /^第[一二三四五六七八九十百]+章/.test(line);
  const isNewItem = (line) => /^(?:\d+[）)]|[一二三四五六七八九十]+、|（[一二三四五六七八九十]+）)/.test(line);
  for (const line of lines) {
    if (/^(?:\d+|[IVX]+)$/.test(line) || /^(?:西南大学|SOUTHWEST UNIVERSITY|867 环境学 初试高分笔记)$/.test(line) || isHeading(line)) continue;
    if (isNewItem(line) && current) { paragraphs.push(current); current = ''; }
    current += line;
  }
  if (current) paragraphs.push(current);
  return paragraphs.map((paragraph) => paragraph.replace(/\s+/g, ' ').trim()).filter((paragraph) => paragraph.length >= 18);
}

function pickParagraph(paragraphs, keywords, fallbackIndex = 0) {
  return paragraphs.find((paragraph) => keywords.some((keyword) => paragraph.includes(keyword))) || paragraphs[fallbackIndex] || paragraphs[0] || '本章正文未提取到可用段落，需人工回到原书核对。';
}

const chapterBodies = normalizedChapters.flatMap((chapter, chapterIndex) => {
  const pagesForChapter = normalizedPages.filter((page) => page.chapter === chapter.title);
  const paragraphs = chapterParagraphs(pagesForChapter);
  const core = pickParagraph(paragraphs, ['是指', '包括', '定义', '概念', '称为', '指的是']);
  const mechanism = pickParagraph(paragraphs, ['由于', '因为', '导致', '从而', '影响', '形成', '过程']);
  const governance = pickParagraph(paragraphs, ['防治', '治理', '控制', '措施', '监测', '评价', '管理', '保护', '处理']);
  const pitfalls = paragraphs.length > 1 ? `${paragraphs[0]} ${paragraphs[1]}` : core;
  const common = { chapter: chapter.title, sourcePages: [chapter.page, chapter.endPage], sourceAnchor: chapter.sourceAnchor, generation: { model: 'databricks-gpt-5-6-luna', generatedAt: new Date().toISOString(), method: 'chapter-local extraction; human review required' } };
  return [
    { ...common, id: `baseline-ch${String(chapterIndex + 1).padStart(2, '0')}-concept`, title: `第${chapterIndex + 1}章 · 核心概念`, tags: ['原书基线', `第${chapterIndex + 1}章`, '核心概念'], prompt: `请定义第${chapterIndex + 1}章的一个核心概念，并说明其边界或构成。`, answer: core },
    { ...common, id: `baseline-ch${String(chapterIndex + 1).padStart(2, '0')}-mechanism`, title: `第${chapterIndex + 1}章 · 机制/因果链`, tags: ['原书基线', `第${chapterIndex + 1}章`, '机制因果'], prompt: `请按“原因/输入 → 过程 → 结果”复述第${chapterIndex + 1}章的一条机制或因果链。`, answer: mechanism },
    { ...common, id: `baseline-ch${String(chapterIndex + 1).padStart(2, '0')}-governance`, title: `第${chapterIndex + 1}章 · 治理/答题框架`, tags: ['原书基线', `第${chapterIndex + 1}章`, '治理框架'], prompt: `如果以本章内容组织一道治理或论述题，你会写出哪些关键措施、步骤或评价点？`, answer: governance },
    { ...common, id: `baseline-ch${String(chapterIndex + 1).padStart(2, '0')}-pitfall`, title: `第${chapterIndex + 1}章 · 易错辨析`, tags: ['原书基线', `第${chapterIndex + 1}章`, '易错辨析'], prompt: `请辨析本章中两个容易混淆的事实、概念或判断条件，并指出不能简单等同的地方。`, answer: pitfalls },
  ].map((card) => ({ ...card, body: card.answer }));
});
const cardOutput = `// Generated from the 12 chapter ranges in structured.md. Do not edit manually.\nexport type BaselineCard = { id: string; title: string; chapter: string; tags: string[]; prompt: string; answer: string; body: string; sourcePages: [number, number]; sourceAnchor: string; generation: { model: string; generatedAt: string; method: string } };\nexport const baselineCards: BaselineCard[] = ${JSON.stringify(chapterBodies, null, 2)};\n`;
fs.writeFileSync(path.resolve('src/generated-baseline-cards.ts'), cardOutput);
const report = `# 867 原书基线记忆卡审核报告\n\n- 生成日期：${new Date().toISOString().slice(0, 10)}\n- 生成模型标记：\`databricks-gpt-5-6-luna\`\n- 来源：\`books/867-chushi-notes/.cangjie/source/structured.md\`\n- 覆盖章节：12/12\n- 卡片总数：${chapterBodies.length}\n- 每章卡片：4 张（核心概念、机制/因果链、治理/答题框架、易错辨析）\n- 已自动通过：0（基线卡全部要求人工审核）\n- 待审核：${chapterBodies.length}\n- 拒绝：0\n\n## 章节覆盖\n\n${normalizedChapters.map((chapter, index) => `- ${index + 1}. ${chapter.title}：4 张，答案非空，来源第 ${chapter.page}–${chapter.endPage} 页，锚点 \`${chapter.sourceAnchor}\``).join('\n')}\n\n## 审核注意项\n\n- 卡片由本地逐页读取、章节范围识别和正文片段抽取生成；没有添加来源之外的事实。\n- “核心概念”和“机制/因果链”需要核对答案是否完整覆盖提示中的概念边界或因果顺序。\n- “治理/答题框架”需要核对所抽片段是否足以形成完整措施链，必要时补充同章正文中的采分点。\n- “易错辨析”当前提供同章两个正文片段作为对照材料，需人工确认它们确实构成易混淆关系，不能把抽取片段直接当成标准答案。\n- 审核通过前所有卡片保持“待审核”，不自动进入正式题库。\n`;
fs.writeFileSync(path.resolve('books/867-chushi-notes/BASELINE_CARDS_REVIEW.md'), report);
