import fs from 'node:fs';
import path from 'node:path';

const source = path.resolve('books/867-chushi-notes/.cangjie/source/structured.md');
const output = path.resolve('src/book-index.ts');
const text = fs.readFileSync(source, 'utf8').replace(/\r\n/g, '\n');
const chunks = text.split(/^===== PAGE (\d+) =====\s*$/m);
const pages = [];
for (let i = 1; i < chunks.length; i += 2) {
  const page = Number(chunks[i]);
  const raw = chunks[i + 1].trim();
  if (!raw) continue;
  const lines = raw.split('\n');
  const headings = lines.filter((line) => /^(#{1,6})\s+/.test(line) || /^(第[一二三四五六七八九十百]+章)\s*/.test(line));
  const title = headings[0]?.replace(/^#+\s*/, '').trim() || `第 ${page} 页`;
  pages.push({ page, title, text: raw, headings });
}
const chapters = [];
for (const page of pages) {
  const matches = page.text.match(/^#\s+(.+)$/gm) ?? [];
  for (const match of matches) {
    const title = match.replace(/^#\s+/, '').trim();
    if (!chapters.some((item) => item.title === title)) chapters.push({ title, page: page.page });
  }
}
const content = `// Generated by scripts/generate-book-index.mjs from structured.md.\nexport type BookPage = { page: number; title: string; text: string; headings: string[] };\nexport type BookChapter = { title: string; page: number };\nexport const bookSource = 'books/867-chushi-notes/.cangjie/source/structured.md';\nexport const bookPages: BookPage[] = ${JSON.stringify(pages)};\nexport const bookChapters: BookChapter[] = ${JSON.stringify(chapters)};\n`;
fs.writeFileSync(output, content);
console.log(`Generated ${pages.length} pages and ${chapters.length} chapters → ${output}`);
